import {test,expect} from '@playwright/test';

test('account and preferences save separately across personas and refresh',async({page})=>{
  await page.goto('/profile');
  await page.getByLabel('Display name').fill('Sample Officer');
  await page.getByLabel('Contact email').fill('sample@example.invalid');
  await page.getByLabel('Designation').fill('Case coordinator');
  await page.getByRole('button',{name:'Save changes',exact:true}).click();
  await expect(page.locator('.profile-link')).toContainText('Sample Officer');
  await page.locator('.settings-nav').getByRole('button',{name:'Preferences',exact:true}).click();
  await expect(page.getByLabel('Display name')).toHaveCount(0);
  await page.getByLabel('Language', {exact:true}).selectOption('Hindi');
  await page.getByLabel('Time zone').selectOption('UTC');
  await page.getByLabel('Date format').selectOption('YYYY-MM-DD');
  await page.getByLabel('Show workspace notifications').uncheck();
  await page.getByRole('button',{name:'Save changes',exact:true}).click();
  await expect(page.getByRole('status').filter({hasText:'Changes saved'})).toBeVisible();
  await page.reload();
  await page.locator('.settings-nav').getByRole('button',{name:'Preferences',exact:true}).click();
  await expect(page.getByLabel('Language',{exact:true})).toHaveValue('Hindi');
  await expect(page.getByLabel('Show workspace notifications')).not.toBeChecked();
  await page.locator('.settings-nav').getByRole('button',{name:'Account',exact:true}).click();
  await expect(page.getByLabel('Contact email')).toHaveValue('sample@example.invalid');
  await page.getByLabel('Demo persona').selectOption('reviewer');
  await expect(page.getByLabel('Display name')).toHaveValue('Demo Reviewer');
  await page.getByLabel('Demo persona').selectOption('guest');
  await expect(page.getByLabel('Display name')).toHaveValue('Guest Viewer');
  await page.getByLabel('Display name').fill('Sample Guest');
  await page.getByRole('button',{name:'Save changes',exact:true}).click();
  await expect(page.getByRole('status').filter({hasText:'Changes saved'})).toBeVisible();
  await page.reload();
  await expect(page.getByLabel('Display name')).toHaveValue('Sample Guest');
  await page.request.post('/api/demo',{data:{type:'role',role:'officer'}});
  await page.request.post('/api/demo',{data:{type:'settings',language:'English',notifications:true,timeZone:'Asia/Kolkata',dateFormat:'DD MMM YYYY'}});
});

test('reviewer restrictions and restoration persist and are enforced for guest',async({page})=>{
  await page.goto('/profile');
  await page.getByLabel('Demo persona').selectOption('reviewer');
  await expect(page.getByLabel('Display name')).toHaveValue('Demo Reviewer');
  await page.locator('.settings-nav').getByRole('button',{name:'Permissions',exact:true}).click();
  const row=page.locator('.list-row').filter({hasText:'PEN-A'});
  await row.getByRole('button',{name:'Restrict access',exact:true}).click();
  await expect(row.getByRole('button',{name:'Restore access',exact:true})).toBeVisible();
  await page.reload();
  await page.locator('.settings-nav').getByRole('button',{name:'Permissions',exact:true}).click();
  await expect(row.getByRole('button',{name:'Restore access',exact:true})).toBeVisible();
  await page.locator('.settings-nav').getByRole('button',{name:'Account',exact:true}).click();
  await page.getByLabel('Demo persona').selectOption('guest');
  await expect(page.getByLabel('Demo persona')).toHaveValue('guest');
  await expect.poll(async()=> (await page.request.get('/api/demo?kind=source&id=PEN-A')).status()).toBe(403);
  await page.getByLabel('Demo persona').selectOption('reviewer');
  await expect(page.getByLabel('Display name')).toHaveValue('Demo Reviewer');
  await page.locator('.settings-nav').getByRole('button',{name:'Permissions',exact:true}).click();
  await row.getByRole('button',{name:'Restore access',exact:true}).click();
  await expect(row.getByRole('button',{name:'Restrict access',exact:true})).toBeVisible();
  await page.locator('.settings-nav').getByRole('button',{name:'Account',exact:true}).click();
  await page.getByLabel('Demo persona').selectOption('guest');
  await expect(page.getByLabel('Demo persona')).toHaveValue('guest');
  await expect.poll(async()=> (await page.request.get('/api/demo?kind=source&id=PEN-A')).status()).toBe(200);
  expect((await page.request.get('/api/demo?kind=source&id=RESTRICTED')).status()).toBe(403);
});
