import {test,expect} from '@playwright/test';

test('approved work records a follow-up and a role-separated local dispatch receipt',async({page})=>{
 test.setTimeout(360000);
 await page.goto('/customize');
 await page.getByRole('button',{name:'Examples',exact:true}).click();
 const created=page.waitForResponse(r=>r.url().endsWith('/api/scenarios')&&r.request().method()==='POST');
 await page.getByTestId('realistic-6').click();
 const run=(await (await created).json()).run;
 const ref=run.evidenceReferences[0];
 await page.goto('/projects/grievance/cases/'+ref.caseId+'/evidence');
 const choose=async(id:string)=>{await page.getByLabel('Grievance demo persona').selectOption(id);await expect(page.getByLabel('Grievance demo persona')).toHaveValue(id)};
 await choose('DEMO-U-RV');
 const source=page.locator('.gr-evidence').filter({has:page.getByRole('link',{name:'DEMO-CIR-003.pdf',exact:true})});
 await source.getByRole('button',{name:'Verify',exact:true}).click();
 await page.getByRole('dialog').getByRole('button',{name:'Save',exact:true}).click();
 await expect(page.getByRole('dialog')).toHaveCount(0);
 for(const sourceRef of run.evidenceReferences.slice(1)){
  await page.goto('/projects/grievance/cases/'+sourceRef.caseId+'/evidence');
  const linked=page.locator('.gr-evidence').filter({has:page.getByRole('link',{name:sourceRef.sourceId+'.pdf',exact:true})});
  await linked.getByRole('button',{name:'Verify',exact:true}).click();
  await page.getByRole('dialog').getByRole('button',{name:'Save',exact:true}).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
 }
 await page.goto('/work/'+run.id);
 await page.getByRole('button',{name:'Decisions',exact:true}).click();
 const role=async(id:string)=>{await page.getByLabel('Workflow demo role').selectOption(id);await expect(page.getByLabel('Workflow demo role')).toHaveValue(id)};
 await role('DEMO-U-DA');
 await page.getByRole('button',{name:'Request review',exact:true}).click();
 await role('DEMO-U-RV');
 await page.getByRole('button',{name:'Verify section review',exact:true}).click();
 await page.getByRole('dialog').getByLabel('Section review comments').fill('Checked source and current version');
 await page.getByRole('dialog').getByRole('button',{name:'Save',exact:true}).click();
 await role('DEMO-U-AP');
 await page.getByRole('button',{name:'Approve version',exact:true}).click();
 await page.getByRole('dialog').getByLabel('Review comments').fill('Approved after independent review');
 await page.getByRole('dialog').getByRole('button',{name:'Save',exact:true}).click();
 await role('DEMO-U-DA');
 await page.getByLabel('Work completion reason').fill('Schedule a local follow-up for this demonstration');
 await page.getByText('Schedule follow-up',{exact:true}).click();
 await page.getByLabel('Work follow-up item').fill('Check the sample acknowledgement');
 await page.getByLabel('Work follow-up due').fill('2026-12-01');
 await page.getByRole('button',{name:'Save follow-up',exact:true}).click();
 await expect(page.getByText('Check the sample acknowledgement',{exact:true})).toBeVisible();
 await role('DEMO-U-DS');
 await page.getByRole('button',{name:'Dispatch Demo',exact:true}).click();
 await expect(page.getByText(/LOCAL DEMONSTRATION DISPATCH ONLY/)).toBeVisible();
 const receipt=await page.request.get('/api/demo?kind=dispatch&id='+run.id);
 expect(receipt.status()).toBe(200);
 expect(await receipt.text()).toContain('No network request, email, government writeback or actual pensioner contact occurred.');
 await role('DEMO-U-AP');
 await page.getByRole('button',{name:'Verify local receipt',exact:true}).click();
 await expect(page.getByText(/Local acknowledgement verified by DEMO-U-AP/)).toBeVisible();
 const saved=(await (await page.request.get('/api/demo')).json()).runs.find((item:{id:string})=>item.id===run.id);
 expect(saved.localDispatch.ack.actor).toBe('DEMO-U-AP');
 expect(saved.followUps[0].status).toBe('Open');
});
